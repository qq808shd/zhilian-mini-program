function getDistractors(items, index, correct) {
  const result = [];
  const seen = new Set([correct]);
  for (let step = 1; result.length < 3 && step <= items.length * 2; step += 1) {
    const candidate = items[(index + step * 23) % items.length].summary;
    if (!seen.has(candidate)) {
      seen.add(candidate);
      result.push(candidate);
    }
  }
  return result;
}

function buildQuestions(items) {
  const letters = ["A", "B", "C", "D"];
  return items.map((item, index) => {
    const answerIndex = index % letters.length;
    const optionTexts = getDistractors(items, index, item.summary);
    optionTexts.splice(answerIndex, 0, item.summary);
    return {
      id: `q-three-character-word-${createStableSuffix(item.title)}`,
      moduleId: "verbal",
      topicId: "three-character-word",
      knowledgeId: item.id,
      stem: `“${item.title}”通常用来表示什么？`,
      options: optionTexts.map((text, optionIndex) => ({
        id: letters[optionIndex],
        text
      })),
      answer: letters[answerIndex],
      explanation: item.detail === item.summary
        ? `释义：${item.summary}`
        : `释义：${item.summary}\n${item.detail}`
    };
  });
}

const threeCharacterWordQuestions = buildQuestions(threeCharacterWordKnowledge);

