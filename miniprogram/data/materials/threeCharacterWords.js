function mergeWords(items) {
  const merged = [];
  const byTitle = {};
  items.forEach((item) => {
    const existing = byTitle[item.title];
    if (!existing) {
      const next = { ...item };
      byTitle[item.title] = next;
      merged.push(next);
      return;
    }
    if (item.summary.length > existing.summary.length) existing.summary = item.summary;
    if (item.example) existing.example = item.example;
    if (item.category !== "常用比喻词") existing.category = item.category;
  });
  return merged;
}

function createStableSuffix(value) {
  let hash = 2166136261;
  Array.from(value).forEach((character) => {
    hash ^= character.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  });
  return (hash >>> 0).toString(36);
}

